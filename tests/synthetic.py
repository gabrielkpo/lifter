"""Synthetic Garmin MCP answers, shaped like garmin-mcp-remote's curated JSON.

No real health data: every value is generated by the tests.
"""

from datetime import date, timedelta

from lifter.sync import store_payload


def activity(
    activity_id: int,
    day: date,
    *,
    load: float | None,
    minutes: float = 60,
    activity_type: str = "running",
) -> dict:
    payload = {
        "id": activity_id,
        "name": f"Synthetic {activity_type}",
        "type": activity_type,
        "start_time_local": f"{day.isoformat()} 07:00:00",
        "duration_seconds": minutes * 60,
        "distance_meters": 10000.0,
        "avg_hr_bpm": 145,
    }
    if load is not None:
        payload["training_load"] = load
    return payload


def hr_zones(seconds: list[float]) -> list[dict]:
    return [
        {"zoneNumber": i + 1, "secsInZone": s, "zoneLowBoundary": 100 + 15 * i}
        for i, s in enumerate(seconds)
    ]


def sleep(hours: float | None, resting_hr: float | None, score: int = 80) -> dict:
    payload = {"sleep_score": score}
    if hours is not None:
        payload["sleep_seconds"] = round(hours * 3600)
    if resting_hr is not None:
        payload["resting_heart_rate_bpm"] = resting_hr
    return payload


def hrv(day: date, ms: float) -> dict:
    return {"date": day.isoformat(), "last_night_avg_hrv_ms": ms, "status": "BALANCED"}


def load_days(conn, first_day: date, days: list[dict]) -> None:
    """Store one synthetic day per dict: keys load, hrv, rhr, sleep_hours (all optional)."""
    next_id = 1000
    for offset, d in enumerate(days):
        day = first_day + timedelta(days=offset)
        key = day.isoformat()
        if d.get("load") is not None:
            next_id += 1
            store_payload(
                conn, "get_activity", str(next_id), {}, activity(next_id, day, load=d["load"])
            )
        if d.get("hrv") is not None:
            store_payload(conn, "get_hrv_data", key, {}, hrv(day, d["hrv"]))
        if d.get("rhr") is not None or d.get("sleep_hours") is not None:
            store_payload(
                conn, "get_sleep_summary", key, {}, sleep(d.get("sleep_hours"), d.get("rhr"))
            )
