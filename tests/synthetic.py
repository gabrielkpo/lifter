"""Synthetic Garmin MCP answers, shaped like garmin-mcp-remote's curated JSON.

No real health data: every value is generated by the tests.
"""

from datetime import date, timedelta

from lifter.sync import store_payload


def activity(
    activity_id: int,
    day: date,
    *,
    load: float | None,
    minutes: float = 60,
    activity_type: str = "running",
) -> dict:
    payload = {
        "id": activity_id,
        "name": f"Synthetic {activity_type}",
        "type": activity_type,
        "start_time_local": f"{day.isoformat()} 07:00:00",
        "duration_seconds": minutes * 60,
        "distance_meters": 10000.0,
        "avg_hr_bpm": 145,
    }
    if load is not None:
        payload["training_load"] = load
    return payload


def hr_zones(seconds: list[float]) -> list[dict]:
    return [
        {"zoneNumber": i + 1, "secsInZone": s, "zoneLowBoundary": 100 + 15 * i}
        for i, s in enumerate(seconds)
    ]


def sleep(hours: float | None, resting_hr: float | None, score: int = 80) -> dict:
    payload = {"sleep_score": score}
    if hours is not None:
        payload["sleep_seconds"] = round(hours * 3600)
    if resting_hr is not None:
        payload["resting_heart_rate_bpm"] = resting_hr
    return payload


def hrv(day: date, ms: float) -> dict:
    return {"date": day.isoformat(), "last_night_avg_hrv_ms": ms, "status": "BALANCED"}


def load_days(conn, first_day: date, days: list[dict]) -> None:
    """Store one synthetic day per dict: keys load, hrv, rhr, sleep_hours (all optional)."""
    next_id = 1000
    for offset, d in enumerate(days):
        day = first_day + timedelta(days=offset)
        key = day.isoformat()
        if d.get("load") is not None:
            next_id += 1
            store_payload(
                conn, "get_activity", str(next_id), {}, activity(next_id, day, load=d["load"])
            )
        if d.get("hrv") is not None:
            store_payload(conn, "get_hrv_data", key, {}, hrv(day, d["hrv"]))
        if d.get("rhr") is not None or d.get("sleep_hours") is not None:
            store_payload(
                conn, "get_sleep_summary", key, {}, sleep(d.get("sleep_hours"), d.get("rhr"))
            )


def daily_stats(day: date, *, bb_high: int = 85, bb_low: int = 25, stress: int = 30) -> dict:
    return {
        "date": day.isoformat(),
        "total_steps": 9000,
        "active_calories": 600,
        "moderate_intensity_minutes": 20,
        "vigorous_intensity_minutes": 15,
        "resting_heart_rate_bpm": 50,
        "avg_stress_level": stress,
        "max_stress_level": 90,
        "stress_qualifier": "BALANCED",
        "body_battery_charged": 60,
        "body_battery_drained": 55,
        "body_battery_highest": bb_high,
        "body_battery_lowest": bb_low,
        "avg_spo2_percent": 96,
        "lowest_spo2_percent": 90,
        "avg_waking_respiration": 14.5,
    }


def training_readiness(day: date, *snapshots: tuple[str, int, str]) -> list[dict]:
    """Snapshots as (HH:MM, score, level), in any order."""
    return [
        {
            "date": day.isoformat(),
            "timestamp": f"{day.isoformat()}T{hhmm}:00.0",
            "level": level,
            "score": score,
            "feedback": "SYNTHETIC",
            "recovery_time_hours": 12.0,
            "acute_load": 420,
            "hrv_weekly_avg": 61,
        }
        for hhmm, score, level in snapshots
    ]


def training_status(day: date, *, acute: int = 420, chronic: int = 400) -> dict:
    return {
        "date": day.isoformat(),
        # Garmin sends a numeric code; the label lives in the feedback phrase.
        "training_status": 7,
        "training_status_feedback": "PRODUCTIVE_1",
        "fitness_trend": 0,
        "vo2_max_precise": 52.3,
        "acute_load": acute,
        "chronic_load": chronic,
        "load_ratio": round(acute / chronic, 1),
        "acwr_status": "OPTIMAL",
    }
